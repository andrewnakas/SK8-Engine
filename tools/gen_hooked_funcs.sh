#!/bin/bash
# Regenerate generated/skate3_hooked_funcs.h - the list of guest functions the
# superproject overrides.
#
# On Apple, Mach-O has no alias attribute, so DEFINE_REX_FUNC emits a SECOND
# weak function per guest function whose entire body is `b __imp__<name>`. That
# exists so the superproject can override a guest function by defining a strong
# `sub_<addr>`. Only ~80 of 47,889 functions are ever overridden; the rest pay a
# wasted branch and a second icache region on every call, and being `weak` they
# can be neither inlined nor folded, which also blocks LTO from seeing through
# any guest call.
#
# This list lets skate3_init.h emit the stub ONLY where it is needed.
#
# Both failure modes are safe and loud:
#   - a hooked function missing from this list  -> two strong definitions
#                                                  -> duplicate symbol at link
#   - a non-hooked function listed here         -> today's behaviour, no stub
#                                                  removed, harmless
#
# Run from the repo root after adding or removing a REX_FUNC hook.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=generated/skate3_hooked_funcs.h
# Overrides live in src/ and, in Skate 3 Ultimate, in the vendored trainer.
SCAN=(src/)
[ -d ../trainer/src ] && SCAN+=(../trainer/src/)
[ -n "${SKATE3_TRAINER_DIR:-}" ] && SCAN+=("${SKATE3_TRAINER_DIR}/src/")

{
  echo "// Auto-generated by tools/gen_hooked_funcs.sh - DO NOT EDIT."
  echo "// Guest functions the superproject overrides with a strong definition."
  echo "#pragma once"
  echo
  {
    grep -rhoE "REX_FUNC\(sub_[0-9A-Fa-f]+\)" "${SCAN[@]}" | sed -E 's/REX_FUNC\((sub_[0-9A-Fa-f]+)\)/\1/'
    grep -rhoE "__imp__sub_[0-9A-Fa-f]+" "${SCAN[@]}" | sed 's/__imp__//'
  } | sort -u | while read -r n; do
    echo "#define SKATE3_HOOKED_${n} ,"
  done
} > "$OUT"

echo "wrote $OUT with $(grep -c '^#define' "$OUT") hooked functions"

# NOTE: the macro machinery that consumes this list lives in
# generated/skate3_init.h, which is GITIGNORED and is rewritten by a codegen
# run. A verbatim copy is kept in tools/skate3_init_apple_direct_funcs.inc so
# it can be reapplied. Phase 3 of the plan moves this - and the REX_WATCH_CHECK
# and REX_TRACE_ENTER edits - into a codegen `template_dir` override, which is
# the real fix for local edits to a generated header.
